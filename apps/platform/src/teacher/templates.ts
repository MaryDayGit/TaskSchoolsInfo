import type { Question } from '@infoklas/shared/grading';

// Шаблоны НУШ из ІнфоКласа (apps/web/src/pages/teacher/templates.ts).

interface QuizInput {
  title: string;
  questions: Question[];
}

type Opt = [text: string, correct?: boolean];

function single(id: string, prompt: string, opts: Opt[], timeLimitSec = 30): Question {
  const options = opts.map(([text], i) => ({ id: String.fromCharCode(97 + i), text }));
  const correct = opts.findIndex(([, c]) => c);
  return {
    id,
    type: 'single',
    prompt,
    timeLimitSec,
    options,
    correctOptionId: options[correct]!.id,
  };
}

function multiple(id: string, prompt: string, opts: Opt[], timeLimitSec = 40): Question {
  const options = opts.map(([text], i) => ({ id: String.fromCharCode(97 + i), text }));
  const correctOptionIds = options.filter((_, i) => opts[i]![1]).map((o) => o.id);
  return { id, type: 'multiple', prompt, timeLimitSec, options, correctOptionIds };
}

function text(id: string, prompt: string, acceptedAnswers: string[], timeLimitSec = 40): Question {
  return { id, type: 'text', prompt, timeLimitSec, acceptedAnswers };
}

